// 求值器 worker 的源码（`eval` 内联，插件因此保持单文件；worker 是唯一能被强杀的边界）。
//
// ABI：`run(程序, 程序名, 输入, 上限)` → `[status u8][len u32 LE][payload]`；
// 状态 0 = 结果、1 = 错误、2 = 超限值的形状。trap（栈溢出之类）会废掉这一代实例，
// 宿主终止整个 worker，下一次调用重新装载。
export const JAQ_WORKER_SOURCE = [
  "const { parentPort, workerData } = require('node:worker_threads');",
  "const { readFileSync } = require('node:fs');",
  "const engine = new WebAssembly.Module(readFileSync(workerData.wasm));",
  'const imports = WebAssembly.Module.imports(engine);',
  "if (imports.length !== 0) throw new Error('expected a zero-import engine, got ' + imports.length);",
  'const encoder = new TextEncoder(); const decoder = new TextDecoder();',
  'const instantiate = () => new WebAssembly.Instance(engine, {}).exports;',
  'const exports_ = instantiate();',
  'function invoke(message) {',
  '  const put = (text) => {',
  '    const bytes = encoder.encode(text);',
  '    const ptr = exports_.alloc(bytes.length);',
  '    new Uint8Array(exports_.memory.buffer, ptr, bytes.length).set(bytes);',
  '    return { ptr: ptr, len: bytes.length };',
  '  };',
  '  let out; const buffers = [];',
  '  const buffer = (text) => { const b = put(text); buffers.push(b); return b; };',
  '  if (message.kind === "load") {',
  '    const input = buffer(message.input);',
  '    out = exports_.load_document(input.ptr, input.len);',
  '  } else {',
  '    const program = buffer(message.program); const path = buffer(message.path);',
  '    if (message.handle !== undefined) {',
  '      const name = buffer(message.inputName ?? "");',
  '      out = exports_.run_document(message.handle, program.ptr, program.len, path.ptr, path.len, name.ptr, name.len, message.maxBytes);',
  '    } else {',
  '      const input = buffer(message.input);',
  '      out = exports_.run(program.ptr, program.len, path.ptr, path.len, input.ptr, input.len, message.maxBytes);',
  '    }',
  '  }',
  '  const view = new DataView(exports_.memory.buffer);',
  '  const status = view.getUint8(out);',
  '  const len = view.getUint32(out + 1, true);',
  '  const payload = decoder.decode(new Uint8Array(exports_.memory.buffer, out + 5, len));',
  '  exports_.dealloc(out, 5 + len);',
  '  for (const b of buffers) exports_.dealloc(b.ptr, b.len);',
  '  return status === 1',
  '    ? { status: 1, message: payload }',
  '    : { status: status, data: JSON.parse(payload) };',
  '}',
  "parentPort.postMessage({ kind: 'ready' });",
  "parentPort.on('message', (message) => {",
  '  try { parentPort.postMessage({ id: message.id, response: invoke(message) }); }',
  '  catch (cause) {',
  "    parentPort.postMessage({ id: message.id, trap: String((cause && cause.message) || cause) });",
  '  }',
  '});',
].join('\n');
