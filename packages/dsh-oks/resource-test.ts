import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {registerHooks} from 'node:module';
import {createKtools} from './src/ktools.ts';
import {createJaqEngine} from './src/jaq.ts';
import {LIBRARY_URI,LIBRARY_PATH,BUILTIN_LIBRARY_URI} from './src/resource-path.ts';
import {parseDraft} from './src/draft/document.ts';
import {createDraftBackend} from './src/draft/backend.ts';
import {createDraftTools} from './src/draft/tools.ts';
const hook=registerHooks({load(url,context,next){return url.endsWith('.md')?{format:'module',source:`export default ${JSON.stringify(readFileSync(new URL(url),'utf8'))}`,shortCircuit:true}:next(url,context);}});
const {createTools}=await import('./src/tools.ts');hook.deregister();
const root=mkdtempSync(join(tmpdir(),'oks-resources-'));
const engine=createJaqEngine(resolve(process.argv[2]??'lib/oks-wti.wasm'));
const ktools=createKtools(engine.checkLibrary,engine.run);
let reads=0;let modelMethods=0;
const graph={datasets:{one:{fields:{n:{type:'Int'}}}},types:{},relations:{},tools:{},items:[{key:'datasets/one',names:['One'],doc:'One dataset'}]};
const entry={root,modelHash:'test',settings:{workspaceRoot:root,retention:{auto:{work:null,artifacts:60,materials:60}}}};
const knowledge={ensureWorkspace(){reads++;return entry;},ensureIndex:async()=>({knowledge:graph}),queryKnowledge:(_entry,source,options)=>{modelMethods++;assert.equal(options.inputName,undefined);return engine.runDocument(source,graph,options);}} as any;
const timeContext={zones:new Map(),install(){}} as any;
const tools=createTools({knowledge,ktools,config:undefined,va:{} as any,timeContext,log(){}});
const exec={agent:{session:{id:'resource-test'}}} as any;
const call=async(name:string,args:unknown)=>{const value=await tools.find(t=>t.name===name)!.execute(args as never,exec);assert.deepEqual(value,JSON.parse(JSON.stringify(value)));return value as any;};
const drafts=createDraftTools({knowledge,ktools,timeContext,backend:(entry,file,contextZone)=>createDraftBackend({knowledge,entry,file,contextZone,jq:engine})});
const draftCall=async(name:string,args:unknown)=>await drafts.tools.find(t=>t.name===name)!.execute(args as never,exec) as any;
try {
 assert.ok(tools.some(t=>t.name==='oks_project'));
 assert.ok(!tools.some(t=>t.name==='oks_'+'data'));
 assert.ok(!tools.some(t=>t.name==='oks_knowledge'||t.name.startsWith('work_')));
 await call('oks_read',{path:BUILTIN_LIBRARY_URI,limit:3});assert.equal(reads,0,'builtin source needs no configured workspace');
 const helpFiles=(await call('oks_list',{path:'oks://help/'})).files;
 assert.equal(helpFiles.length,6);
 for(const {name} of helpFiles){
  assert.match(name,/^oks:\/\/help\/[a-z]+\.md$/);
  const text=readFileSync(new URL('./src/help/'+name.split('/').at(-1),import.meta.url),'utf8');
  const page=await call('oks_read',{path:name,offset:2,limit:3});
  assert.deepEqual(page.lines,text.split('\n').slice(1,4).map((text,at)=>({number:at+2,text})));
  assert.equal(page.offset,2);
  await assert.rejects(call('oks_project',{input:name}),/Unknown structured resource/);
 }
 assert.equal(reads,0,'help listing, reading and rejected projection need no model/workspace');
 await assert.rejects(call('oks_read',{path:'oks://help/query'}),/Unknown readonly help file/);
 await assert.rejects(call('oks_read',{path:'oks://help/missing.md'}),/Unknown readonly help file/);
 assert.deepEqual((await call('oks_project',{input:'oks://knowledge',select:"'datasets'.'one'.'fields'.'n'"})).data,{datasets:{one:{fields:{n:{type:'Int'}}}}});
 assert.deepEqual((await call('oks_project',{input:'oks://knowledge',select:'datasets'})).data,{datasets:graph.datasets});
 assert.equal((await call('oks_project',{input:'oks://knowledge',transform:{lib:BUILTIN_LIBRARY_URI,name:'search',args:{query:'One'}}})).data.total,1);
 await call('oks_write',{path:LIBRARY_URI,content:'def first($args): .rows[0].n + $args.add; def graph_names($args): .datasets | keys; def keys_of($args): keys;'});
 assert.ok(existsSync(join(root,LIBRARY_PATH)));
 assert.deepEqual((await call('oks_project',{input:'oks://knowledge',transform:{lib:LIBRARY_URI,name:'graph_names',args:{}}})).data,['one']);
 const composed=await call('oks_project',{input:'oks://knowledge',transform:{lib:BUILTIN_LIBRARY_URI,name:'search',args:{query:'One'}},select:'total,items:len'});
 assert.deepEqual(composed.data,{total:1,'items:len':1});
 const transformCount=modelMethods;
 await assert.rejects(call('oks_project',{input:'oks://knowledge',transform:{lib:BUILTIN_LIBRARY_URI,name:'search'},select:'broken.'}),/select/);
 assert.equal(modelMethods,transformCount,'invalid select does not execute transform');
 for(const extra of [{select:':keys',pointer:''},{transform:{lib:LIBRARY_URI,name:'first',args:{}},offset:0},{transform:{lib:LIBRARY_URI,name:'first',args:{}},project:'Value'},{args:{}}])await assert.rejects(call('oks_project',{input:'oks://knowledge',...extra}),/Expected only/);
 for(const path of ['oks://work/../oks.json','oks://work//bad','oks://work/a#b','oks://memory/other.lib.jq','oks://builtin/tools/ktools.lib.jq','oks://help/query.md','memory/oks/tools/ktools.lib.jq'])await assert.rejects(call('oks_write',{path,content:'null'}));
 const file='oks://work/report.dari';
 const source='<Dari><Pipeline>facts <-data({rows:[{n:9}]}); {facts}</Pipeline></Dari>';
 assert.equal((await call('oks_write',{path:file,content:source})).file,file);
 assert.ok(existsSync(join(root,'.work/report.dari')));
 assert.equal((await call('oks_read',{path:file})).path,file);
 assert.ok((await call('oks_list',{path:'oks://work/'})).files.some(f=>f.name===file));
 assert.ok((await call('oks_list',{path:'oks://memory/'})).files.every(f=>f.name.startsWith('oks://memory/')));
 assert.equal((await call('oks_list',{path:'oks://builtin/tools/'})).files[0].name,BUILTIN_LIBRARY_URI);
 const result=await draftCall('oks_run_answer',{src:file});assert.equal(result.ok,true,JSON.stringify(result));
 assert.equal((await draftCall('oks_project',{input:file+'#facts',transform:{lib:LIBRARY_URI,name:'first',args:{add:1}}})).data,10);
 const before=modelMethods;
 assert.deepEqual((await draftCall('oks_project',{input:file+'#facts',transform:{lib:LIBRARY_URI,name:'keys_of'}})).data,['rows']);
 assert.equal(modelMethods,before,'retained data transforms do not open the model');
 assert.deepEqual((await draftCall('oks_project',{input:file+'#facts',select:'rows'})).data,{rows:[{n:9}]});
 assert.deepEqual((await draftCall('oks_project',{input:file+'#output'})).data,{facts:{rows:[{n:9}]}});
 await call('oks_edit',{path:file,old_string:'{n:9}',new_string:'{n:10}'});
 assert.equal((await draftCall('oks_project',{input:file+'#facts'})).stale,true);
 await draftCall('renew_context',{src:file});await assert.rejects(draftCall('oks_project',{input:file+'#facts'}));
 await call('oks_delete',{path:file});assert.equal(existsSync(join(root,'.work/report.dari')),false);
 console.log('OKS resources: URI boundaries, readonly builtin, help without model, direct method inputs, graph/draft views, selector exclusivity and logical source lifecycle passed');
}finally{drafts.dispose();tools.dispose();engine.dispose();rmSync(root,{recursive:true,force:true});}
