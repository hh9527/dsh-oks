import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createDraftTools} from '../src/draft/tools.ts';
import {checkReceipt,parseInspect,shapeFingerprint} from '../src/draft/check-receipt.ts';
import {checkDesign} from '../src/draft/design.ts';
import {createDraftBackend} from '../src/draft/backend.ts';
import {scalar,record,type Ty} from '../src/draft/typed-types.ts';

const root=mkdtempSync(join(tmpdir(),'check-receipt-'));
let acquired=0;
const entry={root,modelHash:'fixture',settings:{workspaceRoot:root,queryMaxRows:100},runner:{async send(){return {ok:{accepted:true,queries:[{sql:'select 1 n',bindings:[5],max_rows:5,columns:[{name:'n',type:'Int',nullable:false}]}]}};}}};
const knowledge={ensureWorkspace:()=>entry,executorFor(){acquired++;throw new Error('Check must not acquire rows');}};
const exec={agent:{session:{id:'receipt'}}} as any;
const tools=createDraftTools({knowledge:knowledge as any,timeContext:{zones:new Map([[exec.agent.session,{kind:'resolved',timeZone:'UTC'}]])} as any});
const check=tools.tools.find(t=>t.name==='dari_check')!;
const resolve=tools.tools.find(t=>t.name==='dari_resolve')!;
const file=join(root,'receipt.dari');
const source=`data facts = query({take:5});
data unused = {b:1,a:"x"};
figure chart = tree! { BarChart(spec={x:"n",value:"n"},data=facts) };
answer tree! { Answer [p ["ok"]] };`;
const run=async(inspect?:unknown,caller=exec)=>check.execute({src:'receipt.dari',...(inspect?{inspect}:{})} as never,caller) as Promise<any>;
try{
 writeFileSync(file,source);
 const first=await run();assert.equal(first.ok,true,first.text);
 assert.match(first.text,/## unresolved-node-types\n\n## inspect-node-types/);
 assert.match(first.text,/- data.facts: Table\(\{n:Int\}\)/);
 assert.match(first.text,/- figure.chart: Figure\(data=Table\(\{n:Int\}\)\)/);
 const same=await run();assert(!same.text.includes('- data.facts:'));assert(!same.text.includes('- figure.chart:'));
 const forced=await run({data:['facts'],figures:['chart']});
 assert.match(forced.text,/- data.facts: Table\(\{n:Int\}\)/);assert.match(forced.text,/- figure.chart: Figure/);assert(!forced.text.includes('forced'));
 writeFileSync(file,source.replace('{b:1,a:"x"}','{a:"other",b:42}'));
 assert(!(await run()).text.includes('- data.unused:'));
 writeFileSync(file,source.replace('b:1','b:1.5'));
 const changed=await run();assert.match(changed.text,/- data.unused: /);assert(!changed.text.includes('- data.facts:'));
 const bad=source.replace('data unused = {b:1,a:"x"};','data broken = select({from:{f:facts},fields:r=>({n:r.f.missing})});\ndata blocked = select({from:{b:broken},fields:r=>({n:r.b.n})});');
 writeFileSync(file,bad);const failed=await run();assert.equal(failed.ok,false);
 assert.match(failed.text,/## unresolved-node-types\n- data.broken\n- data.blocked/);assert.match(failed.text,/^CheckFailed\n-+\n\n## diagnostics\n- L\d+:\d+/);assert(!failed.text.includes('Upstream'));
 writeFileSync(file,bad.replace('r.f.missing','r.f.n'));const recovered=await run();
 assert.match(recovered.text,/- data.broken: Table/);assert.match(recovered.text,/- data.blocked: Table/);assert(!recovered.text.includes('- data.facts:'));
 const other={agent:{session:{id:'other'}}} as any;const isolated=await run(undefined,other);assert.match(isolated.text,/- data.facts: Table/);
 writeFileSync(file,source);await resolve.execute({src:'receipt.dari'} as never,exec);
 const afterResolve=await run();assert(!afterResolve.text.includes('- data.unused:'));
 const unknown=await run({data:['absent']});assert.equal(unknown.ok,false);assert.match(unknown.text,/Unknown data binding "absent"/);
 writeFileSync(file,'data row = {"周次":1};\ndata a = row.周次;\ndata b = row.周次;');
 const lexical=await run({data:['a']});assert.equal(lexical.ok,false);assert(!lexical.text.includes('Unknown data binding'));assert.equal((lexical.text.match(/row\["周次"\]/g)??[]).length,2);
 const syntaxSource='data broken = 1+*2;\ndata dependent = broken+1;\ndata valid = 1;';
 writeFileSync(file,syntaxSource);const syntaxFailed=await run({data:['broken']});
 assert.equal(syntaxFailed.ok,false);assert.match(syntaxFailed.text,/- data.broken\n- data.dependent/);assert.match(syntaxFailed.text,/- data.valid: Int/);assert(!syntaxFailed.text.includes('Unknown data binding'));
 const syntaxAgain=await run();assert(!syntaxAgain.text.includes('- data.valid: Int'));assert(!syntaxAgain.text.includes('- data.broken: Int'));
 writeFileSync(file,syntaxSource.replace('1+*2','1+2'));const syntaxFixed=await run();
 assert.equal(syntaxFixed.ok,true,syntaxFixed.text);assert.match(syntaxFixed.text,/- data.broken: Int/);assert.match(syntaxFixed.text,/- data.dependent: Int/);assert(!syntaxFixed.text.includes('- data.valid: Int'));
 writeFileSync(file,Array.from({length:25},(_,i)=>`data syntax${i} = 1+*2;`).join('\n'));
 const syntaxCapped=await run();assert.equal(syntaxCapped.ok,false);assert.equal(syntaxCapped.text.split('\n').filter((l:string)=>/^- L\d/.test(l)).length,20);assert.match(syntaxCapped.text,/5 more errors omitted/);
 for(const raw of [null,[],{data:'facts'},{figures:[1]},{data:['']},{data:Array(33).fill('facts')}])assert.throws(()=>parseInspect(raw));
 const table=(nullable:boolean,reverse=false):Ty=>({kind:'table',columns:(reverse?['b','a']:['a','b']).map(name=>({name,type:'Int',nullable}))});
 assert.notEqual(shapeFingerprint(table(false)),shapeFingerprint(table(true)));assert.notEqual(shapeFingerprint(table(false)),shapeFingerprint(table(false,true)));
 assert.equal(shapeFingerprint(record({b:scalar('String'),a:scalar('Int')})),shapeFingerprint(record({a:scalar('Int'),b:scalar('String')})));
 const backend=createDraftBackend({entry:entry as any,file:'receipt.dari',knowledge:knowledge as any,contextZone:()=>({kind:'resolved',timeZone:'UTC'})});
 const many=source+'\n'+Array.from({length:25},(_,i)=>`data bad${i} = select({from:{f:facts},fields:r=>({n:r.f.absent${i}})});`).join('\n');
 const capped=checkReceipt(await checkDesign(many,'receipt.dari',backend)).text;assert.equal(capped.split('\n').filter(l=>/^- L\d/.test(l)).length,20);assert.match(capped,/5 more errors omitted/);
 backend.dispose?.();assert.equal(acquired,0);
 console.log('Type receipts: changed, forced, failure recovery, session isolation, resolve baseline and error limit passed');
}finally{tools.dispose();rmSync(root,{recursive:true,force:true});}
