 const source=base+report('overview','<p>见 <FigureRef ref="severity"/>。</p>'+fig('severity')+fig('details')+fig('severity'))+report('tables',fig('details')+fig('severity'))+'</Dari>';
 write(source);
 const result=await resolve({figures:['figures.severity','figures.details'],reports:['reports.overview','reports.tables']});assert.equal(result.ok,true,JSON.stringify(result));assert.equal(renders,2,'reports share the same rendered figures');
 const embedded=result.reports['reports.overview'].embedded;assert.match(embedded,/^\[/);assert.match(pathOf(embedded),/\.report\.html$/);
