 assert.throws(()=>parseDraft(base+report('broken',fig('unknown'))+'</Dari>'),/Unknown figure/);
 assert.throws(()=>parseDraft(base+report('broken','<p><FigureRef ref="severity"/></p>')+'</Dari>'),/requires a Figure/);
