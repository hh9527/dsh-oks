import assert from 'node:assert/strict';
import {createDraftBackend} from './src/draft/backend.ts';
import {checkDesign} from './src/draft/design.ts';
import {checkReceipt,parseInspect,shapeFingerprint} from './src/draft/check-receipt.ts';
import {scalar,record,type Ty} from './src/draft/typed-types.ts';
import {guidedTools} from './src/guided-tools.ts';
import {createDraftTools} from './src/draft/tools.ts';
import {mkdtempSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const root=mkdtempSync(join(tmpdir(),'check-receipt-'));
let acquired=0;
const entry={root,modelHash:'fixture',settings:{workspaceRoot:root,queryMaxRows:100},runner:{async send(){return {ok:{accepted:true,queries:[{sql:'select 1 n',bindings:[5],limit_slot:0,columns:[{name:'n',type:'Int',nullable:false}]}]}};}}};
const knowledge={ensureWorkspace:()=>entry,executorFor(){acquired++;throw new Error('Check must not acquire rows');}};
const backend=createDraftBackend({entry:entry as any,knowledge:knowledge as any,contextZone:()=>({kind:'resolved',timeZone:'UTC'})});
const exec={agent:{session:{id:'receipt'}}} as any;
const tools=createDraftTools({knowledge:knowledge as any,timeContext:{zones:new Map([[exec.agent.session,{kind:'resolved',timeZone:'UTC'}]])} as any});
const check=tools.tools.find(t=>t.name==='dari_check')!;
const source=`data facts = query({limit:5});
data unused = {b:1,a:"x"};
figure chart = BarChart(spec={x:"n",value:"n"},data=facts);
report report1 = tree! { Report [UseFigure(ref=chart)] };
answer tree! { Answer [UseReport(ref=report1)] };`;
const status=(text:string)=>text.split('\n').filter(x=>x.startsWith('- ')&&!x.includes(': Figure')&&!x.includes(': Table'));
try{
 writeFileSync(join(root,'receipt.dari'),source);
 const basic=await check.execute({src:'receipt.dari'} as never,exec) as any;
 assert.equal(basic.ok,true,basic.text);
 assert.match(basic.text,/- data.facts: t1-[A-Za-z0-9_-]{9}\n/);
 assert.match(basic.text,/- data.unused: t1-/);
 assert.match(basic.text,/- figure.chart: t1-/);
 assert.match(basic.text,/- report.report1: checked\n- answer: checked/);
 assert(!basic.text.includes('Table('));assert(!basic.text.includes('# inspect:'));
 const rendered=check.output.render({} as never,basic as never).map(b=>b.text??'').join('');
 assert.equal(rendered,basic.text);assert(!rendered.includes('"ok"'));
 const inspected=await check.execute({src:'receipt.dari',inspect:{data:['facts'],figures:['chart']}} as never,exec) as any;
 assert.equal(inspected.ok,true);assert.match(inspected.text,/- data.facts: Table\(\{n:Int\}\)/);
 assert.match(inspected.text,/- figure.chart: Figure\(data=Table\(\{n:Int\}\)\)/);
 assert(!inspected.text.includes('x='));assert(!inspected.text.includes('value='));
 assert.deepEqual(status(basic.text),status(inspected.text.split('\n\n# inspect:')[0]));
 // Definition/value edits and record field ordering do not invalidate shape knowledge.
 writeFileSync(join(root,'receipt.dari'),source.replace('{b:1,a:"x"}','{a:"a different value",b:42}').replace('x:"n",value:"n"','x:"n",value:"n",title:"new title"'));
 const same=await check.execute({src:'receipt.dari'} as never,exec) as any;
 assert.equal(same.text,basic.text);
 writeFileSync(join(root,'receipt.dari'),source.replace('b:1','b:1.5'));
 const different=await check.execute({src:'receipt.dari'} as never,exec) as any;
 assert.notEqual(different.text.match(/data.unused: (\S+)/)[1],basic.text.match(/data.unused: (\S+)/)[1]);
 // Failure still exposes valid shapes and marks dependent nodes unavailable.
 const bad=source.replace('data unused = {b:1,a:"x"};','data broken = select({from:{f:facts},fields:r=>({n:r.f.missing})});\ndata blocked = select({from:{b:broken},fields:r=>({n:r.b.n})});');
 writeFileSync(join(root,'receipt.dari'),bad);
 const failed=await check.execute({src:'receipt.dari',inspect:{data:['facts','broken']}} as never,exec) as any;
 assert.equal(failed.ok,false);assert.match(failed.text,/- data.facts: t1-/);assert.match(failed.text,/- data.broken: \?/);assert.match(failed.text,/- data.blocked: \?/);
 assert.match(failed.text,/# errors:\n- L\d+:\d+-L\d+:\d+: .*missing/);assert(!failed.text.includes('Upstream'));
 assert.match(failed.text,/# inspect:\n- data.facts: Table\(\{n:Int\}\)\n- data.broken: \?/);
 const publicCheck=guidedTools([check],knowledge as any).find(t=>t.name==='dari_check')!;
 await assert.rejects(publicCheck.execute({src:'receipt.dari',inspect:{data:['facts']}} as never,exec),e=>e instanceof Error&&e.message.includes('# errors:')&&e.message.includes('# inspect:')&&!e.message.includes('"diagnostics"'));
 const publicResolve=guidedTools(tools.tools,knowledge as any).find(t=>t.name==='dari_resolve')!;
 await assert.rejects(publicResolve.execute({src:'receipt.dari'} as never,exec),e=>e instanceof Error&&e.message.startsWith('CheckFailed\n-----------')&&!e.message.includes('"queries"'));
 writeFileSync(join(root,'receipt.dari'),source);
 const unknown=await check.execute({src:'receipt.dari',inspect:{data:['chart','absent'],figures:['facts']}} as never,exec) as any;
 assert.equal(unknown.ok,false);assert.match(unknown.text,/Unknown data binding "chart"/);assert.match(unknown.text,/Unknown figure binding "facts"/);
 await assert.rejects(check.execute({src:'receipt.dari',inspect:{reports:['report1']}} as never,exec),/only data and figures/);
 for(const raw of [null,[],{data:'facts'},{figures:[1]},{data:['']},{data:Array(33).fill('facts')}])assert.throws(()=>parseInspect(raw));
 const brokenFigure=await checkDesign(source.replace('value:"n"','value:"missing"'),'receipt.dari',backend);
 assert.match(checkReceipt(brokenFigure).text,/- figure.chart: \?/);assert.match(checkReceipt(brokenFigure).text,/- report.report1: \?/);
 const many=source+'\n'+Array.from({length:25},(_,i)=>`data bad${i} = select({from:{f:facts},fields:r=>({n:r.f.absent${i}})});`).join('\n');
 const capped=checkReceipt(await checkDesign(many,'receipt.dari',backend)).text;
 assert.equal(capped.split('\n').filter(l=>/^- L\d/.test(l)).length,20);assert.match(capped,/5 more errors omitted/);
 const table=(nullable:boolean,reverse=false):Ty=>({kind:'table',columns:(reverse?['b','a']:['a','b']).map(name=>({name,type:'Int',nullable}))});
 assert.notEqual(shapeFingerprint(table(false)),shapeFingerprint(table(true)));
 assert.notEqual(shapeFingerprint(table(false)),shapeFingerprint(table(false,true)));
 assert.equal(shapeFingerprint(record({b:scalar('String'),a:scalar('Int')})),shapeFingerprint(record({a:scalar('Int'),b:scalar('String')})));
 assert.equal(shapeFingerprint({kind:'array',element:scalar('Int'),length:1,nullable:false}),shapeFingerprint({kind:'array',element:scalar('Int'),length:9,nullable:false}));
 const syntax=checkReceipt(await checkDesign('data a = ;','receipt.dari',backend));assert.equal(syntax.ok,false);assert.match(syntax.text,/^CheckFailed\n-----------\n\n# ready-status:\n\n# errors:/);
 assert.equal(acquired,0);
 const {checkedBindings:_,...legacy}=await checkDesign(source,"receipt.dari",backend);
 const legacyChars=JSON.stringify(legacy).length;assert(basic.text.length<legacyChars/4);
 console.log(`Compact check receipts passed: default ${basic.text.length} chars vs previous ${legacyChars}; stable shapes, optional inspect, partial failure, 20-error cap and public exceptions; zero business reads`);
}finally{tools.dispose();backend.dispose?.();rmSync(root,{recursive:true,force:true});}
