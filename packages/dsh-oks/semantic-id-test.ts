import assert from 'node:assert/strict';
import { semanticId, internalRef } from './src/semantic-id.ts';
import { semanticKnowledge } from './src/semantic-knowledge.ts';
import { encodePart } from './src/knowledge-graph.ts';
const name="alarm/a#中文%2F!'()*";
const root='datasets/'+encodePart(name);
const ref=root+'#dimensions/'+encodePart('severity/#%');
assert.equal(internalRef(semanticId(ref)),ref);
assert.equal(internalRef('datasets/%252F'),'datasets/%252F');
for(const id of ['device','datasets/a#dimensions/b','datasets/%2f','datasets/a/b','datasets/%','datasets/']) assert.throws(()=>internalRef(id));
const graph:any={datasets:{[name]:{dimensions:{'severity/#%':{canonical_values:['datasets/device'],type:'types/Severity'}},measures:{},fields:{}}},entities:{device:{}},types:{Severity:{values:{critical:{value:'datasets/device'}}}},relations:{},tools:{secret:{}},items:[{key:root,names:['Alarm'],doc:'datasets/device'},{key:ref,names:['Severity'],doc:'severity'}]};
const before=JSON.stringify(graph);
const search=semanticKnowledge(graph,'search',{query:'Severity'});
assert.equal(search.items[0].id,semanticId(ref));
assert.equal(search.items[0].dimension,'severity/#%');
assert(!('key' in search.items[0]));
const card=semanticKnowledge(graph,'card',{id:search.items[0].id});
assert.equal(card.id,search.items[0].id);
assert.deepEqual(card.facts.canonical_values,['datasets/device']);
assert.equal(card.facts.type,'types/Severity');
const dataset=semanticKnowledge(graph,'card',{id:root});
assert.equal(dataset.dataset,name);
assert.equal(dataset.dimensions[0].id,semanticId(ref));
assert.equal(dataset.dimensions[0].dimension,'severity/#%');
assert.equal(dataset.doc,'datasets/device');
const cap=semanticKnowledge(graph,'cap',{cq:{target:{dataset:name},select:[{dimension:'severity/#%'}]}});
assert.equal(cap.target.knowledge_id,root);
assert.equal(cap.select[0].knowledge_id,semanticId(ref));
assert.equal(cap.candidate_intent.nodes[0].entity,name);
assert.equal(cap.candidate_intent.select[0].dimension,'severity/#%');
assert.equal(semanticKnowledge(graph,'card',{id:cap.select[0].knowledge_id}).id,semanticId(ref));
assert.equal(semanticKnowledge(graph,'card',{id:'entities/device'}).id,'entities/device');
assert.equal(semanticKnowledge(graph,'card',{id:'types/Severity/values/critical'}).facts.value,'datasets/device');
for(const id of ['datasets/device','entities/toString','datasets/__proto__','tools/secret'])assert.throws(()=>semanticKnowledge(graph,'card',{id}));
assert.throws(()=>semanticKnowledge(graph,'card',{id:'entities/device',section:'all'}));
assert.equal(JSON.stringify(graph),before);
console.log('Knowledge IDs: navigation round trips, short query names, literals, encoding and immutable graph passed');
